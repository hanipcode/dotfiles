#!/usr/bin/env node

/**
 * pr-split.mjs — Deterministic operations for PR splitting.
 *
 * Used by the pr-split Claude Code skill. All git operations, worktree
 * management, manifest CRUD, verification, and PR creation are handled here.
 * The AI agent only handles: diff analysis, file grouping, descriptions,
 * and user interaction.
 *
 * Directory structure (tree'd per branch):
 *   {project}-pr-worktrees/
 *     {safe-branch}/
 *       manifest.json
 *       01-{slug}/        ← git worktree
 *       02-{slug}/        ← git worktree
 *
 * Zero external dependencies — uses only Node.js built-ins.
 */

import { execSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
  rmSync,
  rmdirSync,
} from "node:fs";
import { basename, dirname, join } from "node:path";

// ─── Helpers ─────────────────────────────────────────────────────────────────

function git(cmd, opts = {}) {
  const { cwd, allowFail = false } = opts;
  try {
    return execSync(`git ${cmd}`, {
      cwd,
      encoding: "utf-8",
      stdio: ["pipe", "pipe", "pipe"],
    }).trim();
  } catch (err) {
    if (allowFail) return "";
    throw err;
  }
}

function run(cmd, opts = {}) {
  const { cwd, allowFail = false, inheritStdio = false } = opts;
  try {
    if (inheritStdio) {
      execSync(cmd, { cwd, stdio: "inherit" });
      return "";
    }
    return execSync(cmd, {
      cwd,
      encoding: "utf-8",
      stdio: ["pipe", "pipe", "pipe"],
    }).trim();
  } catch (err) {
    if (allowFail) return err.stderr || err.stdout || "";
    throw err;
  }
}

function getRepoRoot() {
  return git("rev-parse --show-toplevel");
}

function getRepoName() {
  return basename(getRepoRoot());
}

function getCurrentBranch() {
  return git("branch --show-current");
}

function safeBranchName(branch) {
  return branch.replace(/\//g, "--");
}

function getWorktreeParent() {
  const root = getRepoRoot();
  return join(dirname(root), `${getRepoName()}-pr-worktrees`);
}

function getBranchDir(safeBranch) {
  return join(getWorktreeParent(), safeBranch);
}

function getManifestPath(safeBranch) {
  return join(getBranchDir(safeBranch), "manifest.json");
}

function getPartDir(safeBranch, part) {
  const padded = String(part.order).padStart(2, "0");
  return join(getBranchDir(safeBranch), `${padded}-${part.slug}`);
}

function readManifest(safeBranch) {
  const p = getManifestPath(safeBranch);
  if (existsSync(p)) {
    return JSON.parse(readFileSync(p, "utf-8"));
  }
  return null;
}

function writeManifest(safeBranch, manifest) {
  const p = getManifestPath(safeBranch);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, JSON.stringify(manifest, null, 2) + "\n");
}

function requireManifest(safeBranch) {
  const m = readManifest(safeBranch);
  if (!m) {
    console.error(
      `ERROR: No manifest found at ${getManifestPath(safeBranch)}. Run plan-save first.`,
    );
    process.exit(1);
  }
  return m;
}

function getPart(manifest, order) {
  const part = manifest.parts.find((p) => p.order === order);
  if (!part) {
    console.error(`ERROR: Part ${order} not found.`);
    process.exit(1);
  }
  return part;
}

function now() {
  return new Date().toISOString();
}

function buildPrBody(manifest, part) {
  const activeParts = manifest.parts.filter((p) => p.status !== "merged");

  const reviewLines = activeParts
    .map((p) => {
      if (p.order === part.order) {
        return `- #${p.prNumber} 👈`;
      } else if (p.prNumber) {
        return `- #${p.prNumber}`;
      } else {
        return `- _(pending)_`;
      }
    })
    .join("\n");

  return `## Summary
${part.description}

## Part of
Split from branch \`${manifest.sourceBranch}\` — Part ${part.order}/${part.total}

## Review order
This is PR ${part.order} of ${part.total}. Review in order for best understanding.

${reviewLines}

---
Generated by pr-split skill`;
}

