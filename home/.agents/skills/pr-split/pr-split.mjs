function cmdCleanup() {
  const currentBranch = getCurrentBranch();
  const safeBranch = safeBranchName(currentBranch);
  const manifest = readManifest(safeBranch);

  if (!manifest) {
    console.log("No manifest found. Nothing to clean up.");
    return;
  }

  let cleaned = 0;

  for (const part of manifest.parts) {
    if (part.status === "merged") continue;
    if (!part.prNumber) continue;

    let prState;
    try {
      prState = run(
        `gh pr view ${part.prNumber} --json state --jq '.state'`,
      );
    } catch {
      prState = "UNKNOWN";
    }

    if (prState === "MERGED") {
      console.log(
        `Cleaning part ${part.order}: ${part.branch} (merged as #${part.prNumber})`,
      );

      const wtPath = getPartDir(safeBranch, part);
      git(`worktree remove "${wtPath}" --force`, { allowFail: true });
      git(`branch -d "${part.branch}"`, { allowFail: true });
      git(`branch -D "${part.branch}"`, { allowFail: true });

      part.status = "merged";
      cleaned++;
    }
  }

  console.log(`\nCleaned ${cleaned} merged part(s).`);

  // Check if all parts are merged
  const remaining = manifest.parts.filter((p) => p.status !== "merged");
  if (remaining.length === 0) {
    console.log(
      `All parts merged. Removing branch directory for ${currentBranch}.`,
    );
    const branchDir = getBranchDir(safeBranch);
    rmSync(branchDir, { recursive: true, force: true });

    // Remove worktree parent if empty
    const worktreeParent = getWorktreeParent();
    try {
      const entries = readdirSync(worktreeParent);
      if (entries.length === 0) rmdirSync(worktreeParent);
    } catch {}
    return;
  }

  manifest.updatedAt = now();
  writeManifest(safeBranch, manifest);
}

function cmdSync() {
  const currentBranch = getCurrentBranch();
  const safeBranch = safeBranchName(currentBranch);
  const manifest = requireManifest(safeBranch);

  const baseBranch = manifest.baseBranch;

  // Get current diff files with their actions (three-dot = since merge base)
  const nameStatus = git(`diff ${baseBranch}...HEAD --name-status`, {
    allowFail: true,
  })
    .split("\n")
    .filter(Boolean);

  // Also get two-dot diff (actual difference from base tip) to filter out
  // files that were changed on this branch but already merged via other PRs
  const twoDotFiles = new Set(
    git(`diff origin/${baseBranch} HEAD --name-only`, { allowFail: true })
      .split("\n")
      .filter(Boolean),
  );

  const currentFiles = [];
  const currentActions = {};
  for (const line of nameStatus) {
    const [action, file] = line.split("\t");
    if (file && twoDotFiles.has(file)) {
      currentFiles.push(file);
      currentActions[file] = action;
    }
  }
  currentFiles.sort();

  // Build set of files owned by ACTIVE (non-merged) parts
  const activeFiles = new Set();
  for (const part of manifest.parts) {
    if (part.status === "merged") continue;
    for (const file of part.files) {
      activeFiles.add(file);
    }
  }

  // Build set of ALL manifest files (including merged)
  const allManifestFiles = new Set(manifest.parts.flatMap((p) => p.files));

  const currentSet = new Set(currentFiles);

  console.log(`Sync Report for ${currentBranch} (base: ${baseBranch})\n`);

  // 1. Orphan files
  const orphanFiles = currentFiles.filter((f) => !activeFiles.has(f));

  console.log("=== Orphan files (not owned by any active PR) ===");
  if (orphanFiles.length > 0) {
    for (const f of orphanFiles) {
      const action = currentActions[f] || "?";
      const reason = allManifestFiles.has(f)
        ? "owned by merged part"
        : "new file";
      console.log(`  ${action}\t${f} (${reason})`);
    }
  } else {
    console.log("(none)");
  }

  // 2. Removed files
  const removedFiles = [];
  for (const part of manifest.parts) {
    if (part.status === "merged") continue;
    for (const file of part.files) {
      if (!currentSet.has(file)) {
        removedFiles.push({ file, part: part.order });
      }
    }
  }

  console.log("\n=== Removed files (in active parts, no longer in diff) ===");
  if (removedFiles.length > 0) {
    for (const { file, part } of removedFiles) {
      console.log(`  ${file} (part ${part})`);
    }
  } else {
    console.log("(none)");
  }

  // 3. Detect stale parts
  const staleParts = [];

  for (const part of manifest.parts) {
    if (part.status === "merged") continue;

    const worktreePath = getPartDir(safeBranch, part);
    if (!existsSync(worktreePath)) {
      staleParts.push({ part, reason: "no worktree" });
      continue;
    }

    for (const file of part.files) {
      const action = part.fileActions?.[file] || "M";
      if (action === "D") continue;

      const sourceHash = git(`rev-parse "${currentBranch}:${file}"`, {
        allowFail: true,
      });
      const worktreeHash = git(`rev-parse HEAD:${file}`, {
        cwd: worktreePath,
        allowFail: true,
      });

      if (sourceHash && worktreeHash && sourceHash !== worktreeHash) {
        staleParts.push({ part, reason: `stale file: ${file}` });
        break;
      }
    }
  }

  console.log("\n=== Stale parts (worktree out of date) ===");
  if (staleParts.length > 0) {
    for (const { part, reason } of staleParts) {
      console.log(`  Part ${part.order}: ${part.title} (${reason})`);
    }
  } else {
    console.log("(none)");
  }

  // Structured JSON summary
  const summary = {
    orphanFiles: orphanFiles.map((f) => ({
      file: f,
      action: currentActions[f] || "?",
      reason: allManifestFiles.has(f) ? "merged-part" : "new",
    })),
    removedFiles,
    staleParts: staleParts.map((s) => ({
      order: s.part.order,
      reason: s.reason,
    })),
  };

  console.log("\n=== SYNC_JSON ===");
  console.log(JSON.stringify(summary));

  // Run validation as final gate
  const vResult = runValidation({ skipWorktreeCheck: true });
  printValidation(vResult);
  if (!vResult.pass) {
    process.exit(1);
  }
}

function runValidation({ skipWorktreeCheck = false } = {}) {
  const currentBranch = getCurrentBranch();
  const safeBranch = safeBranchName(currentBranch);
  const manifest = readManifest(safeBranch);

  if (!manifest) {
    return { pass: false, errors: ["No manifest found for this branch."], summary: "" };
  }

  const baseBranch = manifest.baseBranch;
  const errors = [];

  // 1. Get all files in the diff (two-dot = actual difference from base tip)
  const diffFiles = new Set(
    git(`diff origin/${baseBranch} HEAD --name-only`, { allowFail: true })
      .split("\n")
      .filter(Boolean),
  );

  // 2. Build file → part mapping from active parts
  const fileToPart = new Map();
  const activeParts = manifest.parts.filter((p) => p.status !== "merged");
  for (const part of activeParts) {
    for (const file of part.files) {
      if (fileToPart.has(file)) {
        errors.push(
          `DUPLICATE: ${file} is in Part ${fileToPart.get(file)} AND Part ${part.order}`,
        );
      }
      fileToPart.set(file, part.order);
    }
  }
  const manifestFiles = new Set(fileToPart.keys());

  // 3. Orphan files: in diff but not owned by any active part
  const orphans = [...diffFiles].filter((f) => !manifestFiles.has(f)).sort();
  for (const f of orphans) {
    errors.push(`ORPHAN: ${f} is in the diff but not assigned to any PR`);
  }

  // 4. Stale files: in active parts but no longer in diff
  const stale = [...manifestFiles].filter((f) => !diffFiles.has(f)).sort();
  for (const f of stale) {
    errors.push(
      `STALE: ${f} is in Part ${fileToPart.get(f)} but no longer in the diff`,
    );
  }

  // 5. Check worktree file hashes match source branch
  if (!skipWorktreeCheck) {
    for (const part of activeParts) {
      const worktreePath = getPartDir(safeBranch, part);
      if (!existsSync(worktreePath)) {
        errors.push(
          `MISSING_WORKTREE: Part ${part.order} (${part.slug}) has no worktree`,
        );
        continue;
      }

      for (const file of part.files) {
        const action = part.fileActions?.[file] || "M";
        if (action === "D") continue;

        const sourceHash = git(`rev-parse "${currentBranch}:${file}"`, {
          allowFail: true,
        });
        const worktreeHash = git(`rev-parse HEAD:${file}`, {
          cwd: worktreePath,
          allowFail: true,
        });

        if (sourceHash && worktreeHash && sourceHash !== worktreeHash) {
          errors.push(
            `OUT_OF_SYNC: Part ${part.order} file ${file} differs from source branch`,
          );
        }
      }
    }
  }

  // 6. Check numbering consistency
  const orders = activeParts.map((p) => p.order).sort((a, b) => a - b);
  const expectedTotal = activeParts.length;
  for (let i = 0; i < orders.length; i++) {
    if (orders[i] !== i + 1) {
      errors.push(
        `NUMBERING: Expected part ${i + 1} but found part ${orders[i]}`,
      );
    }
  }
  for (const part of activeParts) {
    if (part.total !== expectedTotal) {
      errors.push(
        `TOTAL_MISMATCH: Part ${part.order} has total=${part.total} but expected ${expectedTotal}`,
      );
    }
  }

  const summary = `${currentBranch} → ${baseBranch} | ${diffFiles.size} diff files, ${manifestFiles.size} manifest files, ${activeParts.length} active parts`;
  return { pass: errors.length === 0, errors, summary };
}

function printValidation(result) {
  console.log(`\nValidate: ${result.summary}\n`);
  if (result.pass) {
    console.log("PASS: All files accounted for. No issues found.");
  } else {
    console.log(`FAIL: ${result.errors.length} issue(s) found:\n`);
    for (const err of result.errors) {
      console.log(`  ✗ ${err}`);
    }
  }
}

function cmdValidate() {
  const result = runValidation();
  printValidation(result);
  process.exit(result.pass ? 0 : 1);
}

