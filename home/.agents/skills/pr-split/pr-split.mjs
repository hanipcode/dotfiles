function cmdPlanSave() {
  const input = readFileSync("/dev/stdin", "utf-8");
  let plan;
  try {
    plan = JSON.parse(input);
  } catch {
    console.error("ERROR: Invalid JSON on stdin");
    process.exit(1);
  }

  // Validate no duplicate files across parts
  const allFiles = plan.parts.flatMap((p) => p.files);
  const dups = allFiles.filter((f, i) => allFiles.indexOf(f) !== i);
  if (dups.length > 0) {
    console.error(
      `ERROR: Duplicate files across parts: ${[...new Set(dups)].join(", ")}`,
    );
    process.exit(1);
  }

  const repoName = getRepoName();
  const currentBranch = getCurrentBranch();
  const safeBranch = safeBranchName(currentBranch);

  const existing = readManifest(safeBranch);
  const total = plan.parts.length;

  const manifest = {
    version: 2,
    repoName,
    sourceBranch: currentBranch,
    baseBranch: plan.baseBranch,
    featureTag: plan.featureTag,
    createdAt: existing?.createdAt || now(),
    updatedAt: now(),
    parts: plan.parts.map((p) => ({
      order: p.order,
      total,
      slug: p.slug,
      branch: p.branch,
      title: p.title,
      description: p.description,
      files: p.files,
      fileActions: p.fileActions,
      status: "pending",
      prNumber: null,
      prUrl: null,
    })),
  };

  writeManifest(safeBranch, manifest);
  console.log(`Manifest saved to ${getManifestPath(safeBranch)}`);
}

function cmdExecute(partNumber) {
  if (!partNumber) {
    console.error("Usage: pr-split.mjs execute <part-number>");
    process.exit(1);
  }
  const order = parseInt(partNumber, 10);
  const currentBranch = getCurrentBranch();
  const safeBranch = safeBranchName(currentBranch);
  const manifest = requireManifest(safeBranch);
  const part = getPart(manifest, order);

  const worktreePath = getPartDir(safeBranch, part);

  // Clean up existing worktree if present
  if (existsSync(worktreePath)) {
    console.log(`Removing existing worktree at ${worktreePath}...`);
    git(`worktree remove "${worktreePath}" --force`, { allowFail: true });
    git(`branch -D "${part.branch}"`, { allowFail: true });
  }

  // Create worktree from base branch
  const branchDir = getBranchDir(safeBranch);
  console.log(`Creating worktree: ${worktreePath}`);
  mkdirSync(branchDir, { recursive: true });
  git(
    `worktree add "${worktreePath}" -b "${part.branch}" "${manifest.baseBranch}"`,
  );

  // Apply files
  console.log("Applying files...");
  for (const file of part.files) {
    const action = part.fileActions?.[file] || "M";

    if (action === "D") {
      console.log(`  rm ${file}`);
      git(`rm "${file}"`, { cwd: worktreePath, allowFail: true });
    } else {
      console.log(`  checkout ${file} (${action})`);
      const fileDir = join(worktreePath, dirname(file));
      mkdirSync(fileDir, { recursive: true });
      git(`checkout "${currentBranch}" -- "${file}"`, { cwd: worktreePath });
    }
  }

  // Commit
  console.log("Committing...");
  git("add -A", { cwd: worktreePath });

  const commitMsg = `${part.title}\n\n${part.description}\n\nSplit from: ${currentBranch}\n\nCo-Authored-By: Claude Opus 4.6 <noreply@anthropic.com>`;
  const msgFile = join(worktreePath, ".pr-split-commit-msg");
  writeFileSync(msgFile, commitMsg);
  git(`commit --no-verify -F "${msgFile}"`, { cwd: worktreePath });
  rmSync(msgFile, { force: true });

  // Update manifest
  part.status = "worktree-created";
  manifest.updatedAt = now();
  writeManifest(safeBranch, manifest);

  console.log(`\nOK: Part ${order} worktree created at ${worktreePath}`);
}

function cmdVerify(partNumber) {
  if (!partNumber) {
    console.error("Usage: pr-split.mjs verify <part-number>");
    process.exit(1);
  }
  const order = parseInt(partNumber, 10);
  const safeBranch = safeBranchName(getCurrentBranch());
  const manifest = requireManifest(safeBranch);
  const part = getPart(manifest, order);
  const worktreePath = getPartDir(safeBranch, part);

  if (!existsSync(worktreePath)) {
    console.error(`ERROR: Worktree not found at ${worktreePath}`);
    process.exit(1);
  }

  console.log(`Verifying part ${order} in ${worktreePath}...`);

  // Install dependencies if needed
  const pkgPath = join(worktreePath, "package.json");
  const nodeModules = join(worktreePath, "node_modules");
  if (existsSync(pkgPath) && !existsSync(nodeModules)) {
    console.log("Installing dependencies...");
    if (existsSync(join(worktreePath, "bun.lockb"))) {
      run("bun install --frozen-lockfile", {
        cwd: worktreePath,
        allowFail: true,
        inheritStdio: true,
      });
    } else if (existsSync(join(worktreePath, "pnpm-lock.yaml"))) {
      run("pnpm install --frozen-lockfile", {
        cwd: worktreePath,
        allowFail: true,
        inheritStdio: true,
      });
    } else if (existsSync(join(worktreePath, "yarn.lock"))) {
      run("yarn install --frozen-lockfile", {
        cwd: worktreePath,
        allowFail: true,
        inheritStdio: true,
      });
    } else {
      run("npm ci", {
        cwd: worktreePath,
        allowFail: true,
        inheritStdio: true,
      });
    }
  }

  // Detect typecheck command
  let typecheckCmd = "";
  if (existsSync(pkgPath)) {
    const pkg = JSON.parse(readFileSync(pkgPath, "utf-8"));
    const scripts = pkg.scripts || {};
    const deps = { ...pkg.dependencies, ...pkg.devDependencies };

    if (existsSync(join(worktreePath, "turbo.json")) && scripts.typecheck) {
      typecheckCmd = "npm run typecheck";
    } else if (scripts.typecheck) {
      typecheckCmd = "npm run typecheck";
    } else if (scripts["type-check"]) {
      typecheckCmd = "npm run type-check";
    } else if (deps.typescript) {
      typecheckCmd = "npx tsc --noEmit";
    }
  }

  if (!typecheckCmd) {
    console.log("WARN: No typecheck command detected. Marking as verified.");
    part.status = "verified";
    manifest.updatedAt = now();
    writeManifest(safeBranch, manifest);
    return;
  }

  console.log(`Running: ${typecheckCmd}`);
  try {
    run(typecheckCmd, { cwd: worktreePath, inheritStdio: true });
    console.log(`\nOK: Typecheck passed for part ${order}`);
    part.status = "verified";
    manifest.updatedAt = now();
    writeManifest(safeBranch, manifest);
  } catch {
    console.error(`\nFAIL: Typecheck failed for part ${order}`);
    process.exit(1);
  }
}

